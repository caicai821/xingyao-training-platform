function makeScores(scores: ScoreMap, overrides: CopyMap = {}): AbilityScores {
  const result = {} as AbilityScores
  for (const dim of ABILITY_DIMENSIONS) {
    const base = defaultCopy[dim.key]
    result[dim.key] = {
      score: scores[dim.key] ?? 3,
      description: base.description,
      strengths: base.strengths,
      concerns: base.concerns,
      observation: base.observation,
      ...overrides[dim.key],
    }
  }
  return result
}

